/**
 * Cryptographic utility for Action Binding and Receipt Fingerprinting.
 * Uses Web Crypto API (crypto.subtle) to generate SHA-256 hashes.
 */

// Canonicalize an object by sorting its keys recursively
export function canonicalize(obj) {
  if (obj === null || typeof obj !== 'object') {
    return obj;
  }
  if (Array.isArray(obj)) {
    return obj.map(canonicalize);
  }
  const sortedKeys = Object.keys(obj).sort();
  const result = {};
  for (const key of sortedKeys) {
    result[key] = canonicalize(obj[key]);
  }
  return result;
}

// Compute SHA-256 hash of a string or canonicalized object
export async function computeSHA256(data) {
  const text = typeof data === 'string' ? data : JSON.stringify(canonicalize(data));
  const msgUint8 = new TextEncoder().encode(text);
  const hashBuffer = await crypto.subtle.digest('SHA-256', msgUint8);
  const hashArray = Array.from(new Uint8Array(hashBuffer));
  return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
}

// Synchronous fallback for display/instant mock generation if needed
export function simpleHash(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash;
  }
  return Math.abs(hash).toString(16).padStart(8, '0');
}

